"""A fixed web address for the studio, through Vercel (optional, free).

The phone link's address (https://<words>.trycloudflare.com) changes every time the tunnel starts.
Vercel can hold one that never changes: a project with no code in it at all, whose single rule
(vercel.json) forwards every request to the tunnel's current address. Each time the tunnel comes
up with a new address the studio re-deploys that one-file project (about 15 s) and points a fixed
alias at it, so https://<alias>.vercel.app always reaches this PC.

Nothing runs ON Vercel. Clipping needs ffmpeg, a GPU, Whisper and jobs that take many minutes;
Vercel's functions stop after 60 s and have no disk, so the work stays on this PC and Vercel only
passes requests through. When this PC is off, the address answers with an error.

Turn it on by putting a token from https://vercel.com/account/tokens in clipper/.env:
    VERCEL_TOKEN=...
    VERCEL_ALIAS=my-clips        (optional: the address becomes https://my-clips.vercel.app)
It also needs Node.js (for `npx vercel`). The passcode still guards everything: requests through
Vercel arrive through the tunnel, and the studio asks for the passcode on anything that did.
"""
from __future__ import annotations

import json
import os
import re
import secrets
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
DIR = HERE / "state" / "vercel" / "clipper-studio"      # the project folder `vercel` deploys
NPX = "npx.cmd" if os.name == "nt" else "npx"


def _env() -> dict:
    from clipper.common import load_env
    return load_env()


def enabled() -> bool:
    return bool(_env().get("VERCEL_TOKEN"))


def alias() -> str:
    """The fixed name: VERCEL_ALIAS, else one made up once and kept (a *.vercel.app name is global,
    so a plain "clipper-studio" is almost certainly someone else's already)."""
    a = _env().get("VERCEL_ALIAS", "").strip().lower()
    if a:
        return re.sub(r"[^a-z0-9-]", "-", a.removesuffix(".vercel.app"))
    f = DIR.parent / "alias.txt"
    if not f.exists():
        f.parent.mkdir(parents=True, exist_ok=True)
        f.write_text(f"clipper-studio-{secrets.token_hex(3)}", encoding="utf-8")
    return f.read_text(encoding="utf-8").strip()


def _vercel(*args: str, timeout: int = 240) -> str:
    token = _env()["VERCEL_TOKEN"]
    r = subprocess.run([NPX, "-y", "vercel@latest", *args, "--token", token], cwd=str(DIR), capture_output=True,
                       text=True, timeout=timeout, encoding="utf-8", errors="replace")
    if r.returncode != 0:
        raise RuntimeError((r.stderr or r.stdout).strip().splitlines()[-1][:300] if (r.stderr or r.stdout) else
                           f"vercel exited {r.returncode}")
    return r.stdout


def deploy(target: str) -> str:
    """Point the fixed address at `target` (the tunnel's current https address). Returns it."""
    DIR.mkdir(parents=True, exist_ok=True)
    (DIR / "vercel.json").write_text(json.dumps({
        "rewrites": [{"source": "/(.*)", "destination": target.rstrip("/") + "/$1"}],
    }, indent=2), encoding="utf-8")
    (DIR / "README.txt").write_text("Generated by the clipper studio (web/vercel_link.py). Every request goes to "
                                    "the studio on its owner's PC.\n", encoding="utf-8")
    out = _vercel("deploy", "--prod", "--yes")
    urls = re.findall(r"https://[a-z0-9.-]+\.vercel\.app", out)
    if not urls:
        raise RuntimeError(f"no deployment address in vercel's answer: {out.strip()[-200:]}")
    name = alias()
    _vercel("alias", "set", urls[-1], f"{name}.vercel.app")
    return f"https://{name}.vercel.app"


if __name__ == "__main__":                 # py -m web.vercel_link https://<words>.trycloudflare.com
    import sys
    print(deploy(sys.argv[1]))
